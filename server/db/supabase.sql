-- ---------------------------------------------------------------------
-- 0. Clean slate (children first)
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS class_booking   CASCADE;
DROP TABLE IF EXISTS class_schedule  CASCADE;
DROP TABLE IF EXISTS class_type      CASCADE;
DROP TABLE IF EXISTS trainer_phone   CASCADE;
DROP TABLE IF EXISTS trainer         CASCADE;
DROP TABLE IF EXISTS member_phone    CASCADE;
DROP TABLE IF EXISTS member          CASCADE;
DROP TABLE IF EXISTS membership_plan CASCADE;
DROP TABLE IF EXISTS user_account    CASCADE;

-- ---------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------
CREATE TABLE user_account (
  user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username       VARCHAR(50)  NOT NULL UNIQUE,
  password_hash  VARCHAR(255) NOT NULL,
  role           VARCHAR(20)  NOT NULL CHECK (role IN ('Admin', 'Trainer', 'Member')),
  account_status VARCHAR(20)  NOT NULL CHECK (account_status IN ('Active', 'Pending')),
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE membership_plan (
  plan_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_name       VARCHAR(100)  NOT NULL UNIQUE,
  duration_months INTEGER       NOT NULL CHECK (duration_months > 0),
  price           NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  billing_type    VARCHAR(50)   NOT NULL,
  class_quota     INTEGER       CHECK (class_quota IS NULL OR class_quota > 0),  -- NULL = unlimited
  is_active       BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE member (
  member_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER      NOT NULL UNIQUE REFERENCES user_account(user_id) ON DELETE CASCADE,
  first_name VARCHAR(100) NOT NULL,
  last_name  VARCHAR(100) NOT NULL,
  email      VARCHAR(100) NOT NULL UNIQUE,
  birth_date DATE         NOT NULL,
  gender     VARCHAR(10)  NOT NULL CHECK (gender IN ('M', 'F', 'Other')),
  -- deleting a plan must never delete members, so the link is just cleared
  plan_id    INTEGER      REFERENCES membership_plan(plan_id) ON DELETE SET NULL,
  start_date DATE,
  end_date   DATE,
  CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE member_phone (
  member_id INTEGER     NOT NULL REFERENCES member(member_id) ON DELETE CASCADE,
  phone     VARCHAR(20) NOT NULL,
  PRIMARY KEY (member_id, phone)
);

CREATE TABLE trainer (
  trainer_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INTEGER      NOT NULL UNIQUE REFERENCES user_account(user_id) ON DELETE CASCADE,
  first_name       VARCHAR(100) NOT NULL,
  last_name        VARCHAR(100) NOT NULL,
  email            VARCHAR(100) NOT NULL UNIQUE,
  specialization   VARCHAR(150) NOT NULL,
  experience_years INTEGER      NOT NULL CHECK (experience_years >= 0),
  hire_date        DATE                      -- NULL until an admin approves
);

CREATE TABLE trainer_phone (
  trainer_id INTEGER     NOT NULL REFERENCES trainer(trainer_id) ON DELETE CASCADE,
  phone      VARCHAR(20) NOT NULL,
  PRIMARY KEY (trainer_id, phone)
);

CREATE TABLE class_type (
  class_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_name     VARCHAR(100) NOT NULL UNIQUE,
  level         VARCHAR(20)  NOT NULL CHECK (level IN ('Beginner', 'Intermediate', 'Advanced'))
);

CREATE TABLE class_schedule (
  schedule_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_type_id   INTEGER     NOT NULL REFERENCES class_type(class_type_id) ON DELETE CASCADE,
  trainer_id      INTEGER     NOT NULL REFERENCES trainer(trainer_id)       ON DELETE CASCADE,
  room_name       VARCHAR(50) NOT NULL,
  class_date      DATE        NOT NULL,
  start_time      TIME        NOT NULL,
  end_time        TIME        NOT NULL,
  max_capacity    INTEGER     NOT NULL CHECK (max_capacity > 0),
  schedule_status VARCHAR(20) NOT NULL DEFAULT 'Open'
                  CHECK (schedule_status IN ('Open', 'Full', 'Cancelled')),
  CHECK (end_time > start_time)
);

CREATE TABLE class_booking (
  booking_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id         INTEGER     NOT NULL REFERENCES member(member_id)            ON DELETE CASCADE,
  schedule_id       INTEGER     NOT NULL REFERENCES class_schedule(schedule_id)  ON DELETE CASCADE,
  booking_time      TIMESTAMPTZ NOT NULL DEFAULT now(),
  booking_status    VARCHAR(20) NOT NULL
                    CHECK (booking_status IN ('Booked', 'Waitlist', 'Attended', 'NoShow', 'Cancelled')),
  waitlist_position INTEGER     CHECK (waitlist_position IS NULL OR waitlist_position > 0),
  -- a waitlist row needs a position; every other status must not have one
  CHECK ((booking_status = 'Waitlist') = (waitlist_position IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- 2. Indexes
-- ---------------------------------------------------------------------
-- One live booking per member per class (cancelled rows don't count) —
-- stops double-booking even if two requests race each other.
CREATE UNIQUE INDEX uq_booking_member_schedule_live
  ON class_booking (member_id, schedule_id)
  WHERE booking_status <> 'Cancelled';

CREATE INDEX idx_booking_schedule_status ON class_booking (schedule_id, booking_status);
CREATE INDEX idx_booking_member          ON class_booking (member_id);
CREATE INDEX idx_schedule_date           ON class_schedule (class_date, start_time);
CREATE INDEX idx_schedule_trainer_date   ON class_schedule (trainer_id, class_date);
CREATE INDEX idx_schedule_room_date      ON class_schedule (room_name, class_date);
CREATE INDEX idx_member_plan             ON member (plan_id);

-- ---------------------------------------------------------------------
-- 3. Lock the tables away from Supabase's public Data API
-- ---------------------------------------------------------------------
-- The Express API connects as the table owner (postgres), which bypasses
-- RLS, so the app keeps working. The anon/authenticated roles used by
-- Supabase's REST/GraphQL API get no rows and no privileges — otherwise
-- anyone with the project URL could read password hashes.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['user_account','membership_plan','member','member_phone',
                           'trainer','trainer_phone','class_type','class_schedule','class_booking']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon', t);
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
      EXECUTE format('REVOKE ALL ON TABLE public.%I FROM authenticated', t);
    END IF;
  END LOOP;
END $$;

