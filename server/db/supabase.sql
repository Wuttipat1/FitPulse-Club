-- =====================================================================
--  FitPulse Club — PostgreSQL schema + seed data (Supabase)
-- ---------------------------------------------------------------------
--  Paste this whole file into Supabase → SQL Editor → New query → Run.
--
--  ⚠  RESET SCRIPT: it DROPS and recreates all 9 FitPulse tables, so
--     running it again wipes every member, booking and schedule.
--
--  Seed dates are relative to the day you run it (CURRENT_DATE), so the
--  demo schedule always starts "today" in Asia/Bangkok time.
--
--  Demo logins:  admin / admin123
--                somchai, ploy, mike / member123
--                praewa, kitti / trainer123   (napat = pending trainer)
-- =====================================================================

